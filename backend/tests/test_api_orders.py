def _order(**overrides):
    values = dict(restaurant_name='Trattoria Verdi', pickup_address='Via Roma 1', delivery_address='Via Po 9',
                  pay=6.5, bonus=1.5, distance_km=2.4)
    values.update(overrides)
    return Order(**values)


