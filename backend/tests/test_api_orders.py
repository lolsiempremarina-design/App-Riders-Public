def test_deleting_the_account_releases_the_orders_in_progress(app, client, people):
    """Before, an order accepted or picked up by a rider who deleted the account stayed blocked forever."""
    with app.app_context():
        db.session.add_all([_order(restaurant_name='Accettato'), _order(restaurant_name='Ritirato')])
        db.session.commit()
        accepted_id, picked_id = [o.id for o in Order.query.order_by(Order.id)]

    _login(client, 'rider1@example.com')
    assert client.post(f'/api/orders/{accepted_id}/accept').status_code == 200
    assert client.post('/api/auth/delete-account', json={'password': 'password'}).status_code == 200
    _login(client, 'rider2@example.com')
    assert client.post(f'/api/orders/{picked_id}/accept').status_code == 200
    assert client.patch(f'/api/orders/{picked_id}/status', json={'status': 'picked_up'}).status_code == 200
    assert client.post('/api/auth/delete-account', json={'password': 'password'}).status_code == 200

    with app.app_context():
        offered, cancelled = db.session.get(Order, accepted_id), db.session.get(Order, picked_id)
        assert (offered.status, offered.rider_id, offered.accepted_at) == ('available', None, None)
        assert (cancelled.status, cancelled.rider_id) == ('cancelled', None) and cancelled.cancelled_at
        # the admin is told about the cancelled one (the riders were deleted, so nobody else to notify)
        titles = [n.title for n in Notification.query.filter_by(user_id=people['admin'])]
        assert 'Order cancelled: Ritirato' in titles
    _login(client, 'boss@example.com')
    assert client.get('/api/orders/available').get_json()['orders'][0]['id'] == accepted_id


def test_a_failed_notice_does_not_hide_the_handed_back_order(app, client, people, monkeypatch):
    from app.api import orders as orders_api

    with app.app_context():
        order = _order()
        db.session.add(order)
        db.session.commit()
        order_id = order.id

    def broken(*args, **kwargs):
        raise RuntimeError('database hiccup')

    monkeypatch.setattr(orders_api, 'announce_handed_back', broken)
    _login(client, 'rider1@example.com')
    assert client.post(f'/api/orders/{order_id}/accept').status_code == 200
    released = client.patch(f'/api/orders/{order_id}/status', json={'status': 'released'})
    assert released.status_code == 200 and released.get_json()['order']['status'] == 'available'
