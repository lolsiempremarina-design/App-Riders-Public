def test_admin_panel_is_only_for_admins(app, client, people):
    anonymous = client.get('/admin/')
    assert anonymous.status_code == 302 and anonymous.headers['Location'].startswith('/accedi?next=')

    _login(client, 'rider1@example.com')
    assert client.get('/admin/').status_code == 403
    assert client.post('/admin/orders/new', data={}).status_code == 403

    _login(client, 'boss@example.com')
    assert client.get('/admin/').status_code == 200

    # bike QR codes are generated by the server (inline SVG with the public address of the bike)
    import segno
    from app.auth.models import Bike
    with app.app_context():
        db.session.add(Bike(bike_id='013-077'))
        db.session.commit()
    page = client.get('/admin/bikes').get_data(as_text=True)
    assert 'qrserver' not in page
    assert segno.make('http://localhost/bici/013-077', error='m').svg_inline(scale=4, border=2) in page

    response = client.post('/admin/orders/new', data={
        'restaurant_name': 'Pizzeria Sole', 'pickup_address': 'Corso Como 3', 'delivery_address': 'Via Tortona 20',
        'pay': '7.00', 'bonus': '2.00', 'distance_km': '3.1', 'offer_minutes': '30', 'due_minutes': '45',
    })
    assert response.status_code == 302
    with app.app_context():
        order = Order.query.one()
        assert order.status == 'available' and order.total == 9.0
        assert order.expires_at > utcnow() and order.due_at > order.expires_at
        # every rider (not the admin) was notified
        assert {n.user_id for n in Notification.query.filter_by(category='consegne')} == {people['rider'], people['other']}
    assert b'Pizzeria Sole' in client.get('/admin/').data


def test_full_delivery_flow_and_earnings(app, client, people):
    with app.app_context():
        db.session.add_all([_order(), _order(restaurant_name='Sushi Kyo', due_at=utcnow() + timedelta(hours=1)),
                            _order(restaurant_name='Scaduto', expires_at=utcnow() - timedelta(minutes=1))])
        db.session.commit()

    _login(client, 'rider1@example.com')
    available = client.get('/api/orders/available').get_json()['orders']
    assert {o['restaurant'] for o in available} == {'Trattoria Verdi', 'Sushi Kyo'}  # expired offer hidden
    sushi = next(o for o in available if o['restaurant'] == 'Sushi Kyo')

    accepted = client.post(f"/api/orders/{sushi['id']}/accept")
    assert accepted.status_code == 200 and accepted.get_json()['order']['status'] == 'accepted'
    assert client.get('/api/orders/active').get_json()['order']['id'] == sushi['id']
    # one order at a time
    other_id = next(o['id'] for o in available if o['restaurant'] == 'Trattoria Verdi')
    assert client.post(f'/api/orders/{other_id}/accept').get_json()['error'] == 'active_order_exists'
    # cannot skip the pickup
    assert client.patch(f"/api/orders/{sushi['id']}/status", json={'status': 'delivered'}).get_json()['error'] == 'invalid_transition'
    assert client.patch(f"/api/orders/{sushi['id']}/status", json={'status': 'picked_up'}).get_json()['order']['status'] == 'picked_up'
    done = client.patch(f"/api/orders/{sushi['id']}/status", json={'status': 'delivered'}).get_json()['order']
    assert done['status'] == 'delivered' and done['on_time'] is True
    assert client.get('/api/orders/active').get_json()['order'] is None

    completed = client.get('/api/orders/completed?period=today').get_json()
    assert [o['restaurant'] for o in completed['orders']] == ['Sushi Kyo']
    assert completed['summary'] == {'deliveries': 1, 'pay': 6.5, 'bonus': 1.5, 'earnings': 8.0,
                                    'distance_km': 2.4, 'on_time_rate': 1.0}
    earnings = client.get('/api/rider/earnings?period=week').get_json()
    assert earnings['summary']['earnings'] == 8.0
    assert earnings['days'][0]['deliveries'] == 1 and earnings['days'][0]['earnings'] == 8.0
    assert client.get('/api/rider/earnings?period=decade').status_code == 422


def test_race_and_release(app, client, people):
    with app.app_context():
        order = _order()
        db.session.add(order)
        db.session.commit()
        order_id = order.id

    _login(client, 'rider1@example.com')
    assert client.post(f'/api/orders/{order_id}/accept').status_code == 200
    _login(client, 'rider2@example.com')
    assert client.post(f'/api/orders/{order_id}/accept').get_json()['error'] == 'order_unavailable'
    assert client.patch(f'/api/orders/{order_id}/status', json={'status': 'released'}).status_code == 404  # not theirs

    _login(client, 'rider1@example.com')
    released = client.patch(f'/api/orders/{order_id}/status', json={'status': 'released'}).get_json()['order']
    assert released['status'] == 'available'
    _login(client, 'rider2@example.com')
    assert client.post(f'/api/orders/{order_id}/accept').status_code == 200


def _titles(app, user_id):
    with app.app_context():
        return [n.title for n in Notification.query.filter_by(user_id=user_id).order_by(Notification.id)]


def test_a_handed_back_order_is_announced_to_the_other_riders(app, client, people):
    """Before, the other riders learned about it only by opening Consegne (every 60 s with push on)."""
    with app.app_context():
        order = _order(expires_at=utcnow() + timedelta(minutes=10))
        db.session.add(order)
        db.session.commit()
        order_id = order.id

    _login(client, 'rider1@example.com')
    assert client.post(f'/api/orders/{order_id}/accept').status_code == 200
    assert client.patch(f'/api/orders/{order_id}/status', json={'status': 'released'}).status_code == 200
    assert _titles(app, people['other']) == ['Available again: Trattoria Verdi']
    assert _titles(app, people['rider']) == []  # not to who handed it back
    assert _titles(app, people['admin']) == []


def test_a_handed_back_order_whose_offer_expired_goes_to_the_admins(app, client, people):
    """Accepted just before its offer expired and handed back: no rider can see it, an admin must offer it again."""
    with app.app_context():
        order = _order(expires_at=utcnow() + timedelta(minutes=1))
        db.session.add(order)
        db.session.commit()
        order_id = order.id

    _login(client, 'rider1@example.com')
    assert client.post(f'/api/orders/{order_id}/accept').status_code == 200
    with app.app_context():
        db.session.get(Order, order_id).expires_at = utcnow() - timedelta(minutes=1)
        db.session.commit()
    assert client.patch(f'/api/orders/{order_id}/status', json={'status': 'released'}).status_code == 200
    assert _titles(app, people['other']) == []  # an order they could not see
    assert _titles(app, people['admin']) == ['Order to offer again: Trattoria Verdi']


